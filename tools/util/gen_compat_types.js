/**
 * @file Generate the package-level type files that both `@fibjs/types` and
 * `fibjs --check` must share.
 *
 * Two files are written into the corpus:
 *
 *   dts/_builtin/globals.d.ts
 *       The global `var`/`function` declarations the ES lib does not provide,
 *       the `interface X extends Class_Y` twins of the class-valued globals,
 *       and the CommonJS wrapper names. It must stay a *script* (no top-level
 *       import/export), otherwise the declarations stop being global.
 *
 *   dts/_builtin/prefixed-modules.d.ts
 *       `fibjs:<module>` / `node:<module>` aliases for every module the
 *       runtime resolves under those prefixes.
 *
 * The files used to be synthesized at `--check` time only, while the published
 * package had no copy of them. They now live in the corpus so the package and
 * the embedded checker use the same text.
 *
 * Run after tools/util/gen_dts.js and before tools/gen_builtin_types.js.
 * tools/idlc.js does both.
 */

const fs = require('fs');
const path = require('path');

const GLOBALS_FILE = 'globals.d.ts';
const PREFIXED_MODULES_FILE = 'prefixed-modules.d.ts';

// Globals the *ES* lib chain already declares as values. `globalThis` is the
// only one the `global` module exports, and redeclaring it would shadow the
// lib's own type.
const LIB_PROVIDED = new Set([
    'globalThis',
]);

function readText(file) {
    return fs.readFileSync(file, 'utf8');
}

/**
 * Write only when the content changed, so a second idlc run leaves mtimes and
 * the working tree untouched.
 */
function writeIfChanged(file, content) {
    if (fs.existsSync(file) && readText(file) === content)
        return false;

    fs.writeFileSync(file, content);
    console.log(`      ✏️  ${path.basename(file)}`);
    return true;
}

/**
 * Build the global declaration file from the generated `global` module.
 *
 * `declare var` (not `const`) is what puts the name on `globalThis`; the value
 * is still the runtime's (the checker never emits, so nothing can assign it).
 *
 * A class-valued global also owns its type name. `interface X extends Class_Y`
 * is used rather than `type X = Class_Y`: a project or a dependency that
 * declares a placeholder `interface X {}` merges with an interface, while a
 * type alias would be a duplicate identifier and take the value down with it
 * (TS2451).
 */
function buildGlobals(dtsDir) {
    const globalDts = readText(path.join(dtsDir, 'module/global.d.ts'));

    const exported = new Set();
    for (const m of globalDts.matchAll(/^\s*(?:const|function)\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*[:<(]/gm))
        exported.add(m[1]);

    const kept = Array.from(exported).filter(n => !LIB_PROVIDED.has(n));

    const classAliases = [];
    for (const m of globalDts.matchAll(/^\s*const\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*:\s*typeof\s+(Class_[A-Za-z0-9_$]+)\s*;/gm))
        if (kept.indexOf(m[1]) >= 0)
            classAliases.push(`interface ${m[1]} extends ${m[2]} {}`);

    const text = [
        '// fibjs globals, generated by tools/util/gen_compat_types.js.',
        '// Shared by @fibjs/types and the built-in --check types.',
        '',
        kept.map(n => `declare var ${n}: typeof import('global').${n};`).join('\n'),
        '',
        '// the class-valued globals also own their type name; an interface',
        '// merges with the placeholders a project may declare',
        classAliases.join('\n'),
        '',
        '// fibjs specific globals without an IDL declaration',
        'declare function gc(): void;',
        '',
        '// the `import.meta` members the module loader installs',
        '// (fibjs/src/base/v8_api/utils.cpp: initImportMeta)',
        'interface ImportMeta {',
        '    url: string;',
        '    dirname: string;',
        '    filename: string;',
        '}',
        '',
        'declare const __filename: string;',
        'declare const __dirname: string;',
        'declare var exports: {',
        '    [k: string]: any;',
        '};',
        'declare var module: {',
        '    exports: typeof exports;',
        '};',
        ''
    ].join('\n');

    return { text, kept };
}

/**
 * The runtime registers every root module under its own name plus the
 * `fibjs:` and `node:` prefixes (`SandBox::installRootModules()`), and the
 * Node compat layer adds the rest (`module`, `buffer`, `stream`, ...).
 *
 * Which names qualify is decided by asking the runtime itself: this generator
 * runs inside fibjs, so `require('node:<name>')` is the same question a user
 * asks. The IMPORT_MODULE list in fibjs/src/base/modules.cpp is not enough
 * because the compatibility layer adds modules dynamically.
 */
function prefixedModuleSupported(name) {
    try {
        require('node:' + name);
        return true;
    } catch (e) {
        return false;
    }
}

function buildPrefixed(dtsDir) {
    const moduleDir = path.join(dtsDir, 'module');
    const aliases = [];

    fs.readdirSync(moduleDir)
        .filter(f => f.endsWith('.d.ts'))
        .sort()
        .forEach(f => {
            const text = readText(path.join(moduleDir, f));
            const declared = /^declare module '([^']+)'/m.exec(text);

            if (!declared)
                return;

            const name = declared[1];

            if (!prefixedModuleSupported(name))
                return;

            // An `export =` module cannot be re-exported with `export *`
            // (TS2498); bind and re-export the entity itself, the shape
            // @types/node gives `node:assert`.
            if (/^\s*export\s*=/m.test(text)) {
                // the local binding needs an identifier:
                // `assert/strict` binds as `assert_strict`
                const bind = name.replace(/[^\w$]/g, '_');

                if (!/^[A-Za-z_$][\w$]*$/.test(bind))
                    throw new Error(`the export = module '${name}' needs an identifier to re-export under fibjs:/node:`);

                aliases.push(`declare module "fibjs:${name}" { import ${bind} = require("${name}"); export = ${bind}; }`);
                aliases.push(`declare module "node:${name}" { import ${bind} = require("${name}"); export = ${bind}; }`);
                return;
            }

            aliases.push(`declare module "fibjs:${name}" { export * from "${name}"; }`);
            aliases.push(`declare module "node:${name}" { export * from "${name}"; }`);
        });

    return {
        count: aliases.length,
        text: [
            '// fibjs: / node: aliases of the root modules, generated by tools/util/gen_compat_types.js.',
            '// The runtime registers them in SandBox::installRootModules().',
            '',
            aliases.join('\n'),
            ''
        ].join('\n')
    };
}

function generate(dtsDir) {
    const outDir = path.join(dtsDir, '_builtin');
    fs.mkdirSync(outDir, { recursive: true });

    const globals = buildGlobals(dtsDir);
    const prefixed = buildPrefixed(dtsDir);

    writeIfChanged(path.join(outDir, GLOBALS_FILE), globals.text);
    writeIfChanged(path.join(outDir, PREFIXED_MODULES_FILE), prefixed.text);

    return {
        globals: globals.kept.length,
        aliases: prefixed.count,
    };
}

module.exports = { generate };
